"""D-B048: one summary of all cases from data/tomo_v1/b5_test/<case>/metrics.json -> summary.md (tables for the note).

  python b5_summary.py
"""
import json

import pandas as pd

from b5_common import REPO, write_manifest

D = REPO / "data" / "tomo_v1" / "b5_test"
RUNS = ["b4", "tomodd/hier", "tomodd/dd", "growclust/catalog", "growclust/default"]


def md(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:.2f}" if isinstance(v, float) else str(v) for v in r.values) + " |")
    return "\n".join(out)


def main():
    L = ["# D-B048 summary (generated by b5_summary.py)", ""]
    files = sorted(D.glob("*/metrics.json"))
    for f in files:
        M = json.loads(f.read_text())
        case = M["case"]
        L += [f"## {case}", "", f"events {M['events']}, linked by dt pairs {M['events_linked']}, dt pairs {M['dt_pairs']}, "
              f"dt {M['dt_data']}, relocated by every run {M['common']}", ""]
        sh = pd.DataFrame(M["shape"])
        un = pd.DataFrame(M["uncertainty"]).set_index("run")
        mi = pd.DataFrame(M["dt_misfit"]).set_index("run")
        rows = []
        for k in RUNS + (["truth"] if M["synthetic"] else []):
            o = sh[(sh.run == k) & (sh.subset == "own")]
            if o.empty:
                continue
            o = o.iloc[0]
            r = dict(run=k, n=int(o.n), shift_h=float((o.shift_e ** 2 + o.shift_n ** 2) ** 0.5), shift_z=o.shift_z,
                     s1=o.sigma1, s2=o.sigma2, s3=o.sigma3, strike=o.strike, dip=o.dip, z_med=o.depth_med,
                     z_p10=o.depth_p10, z_p90=o.depth_p90)
            if k in un.index:
                u = un.loc[k]
                r.update(boot_sh=u.get("boot_sh_med", float("nan")), boot_sz=u.get("boot_sz_med", float("nan")))
            if k in mi.index:
                r.update(rmsP=mi.loc[k, "rms_P"], rmsS=mi.loc[k, "rms_S"])
            rows.append(r)
        L += ["Own relocated sets: centroid shift from B4 (km), PCA sigmas (km), strike/dip (deg), depth (km bsl), "
              "bootstrap std median (km), dt rms in the B4 grids on the common set (s)", "", md(pd.DataFrame(rows)), ""]
        rp = pd.DataFrame(M["relative_positions"])
        pr = pd.DataFrame(M["pairs"])
        sel = rp.merge(pr[["a", "b", "absdiff_med", "absdiff_p90"]], on=["a", "b"])
        sel = sel[["a", "b", "n", "dh_med", "dh_p90", "dz_med", "dz_p90", "absdiff_med", "absdiff_p90"]]
        L += ["Common set: relative position differences (centroid removed) and |pair distance difference| (km)", "",
              md(sel), ""]
        if M["synthetic"]:
            er = pd.DataFrame(M["synthetic_errors"])
            er = er[["run", "subset", "n", "rel_h_med", "rel_h_p90", "rel_z_med", "rel_z_p90", "pair_err_med",
                     "plane_rms_km", "sigma1", "sigma2", "strike", "centroid_z"]]
            L += ["Errors against the truth (km): relative (centroid removed), pair distances, plane thickness", "",
                  md(er), ""]
    (D / "summary.md").write_text("\n".join(L) + "\n")
    write_manifest("b5_summary", D, inputs=files, outputs=[D / "summary.md"], counts={"cases": len(files)})
    print("\n".join(L))


if __name__ == "__main__":
    main()
